import torch
import torch.nn as nn
import torch.nn.functional as F


class QMixer(nn.Module):
    """
    Standard (feedforward) QMIX monotonic mixer. Q_tot = f(agent_qs, state) with
    non-negative weights generated by hypernetworks => dQ_tot/dQ_a >= 0 (monotonicity).
    Reads RAW state only (comm-free) — the isolation guarantee (mirrors MAPPO's critic).

    Init note: canonical QMIX (pymarl) uses default Kaiming-uniform init, but that
    relies on SMAC-style reward scaling and otherwise inflates Q_tot at init (with
    embed=32 the abs'd weights amplify the per-agent sum, and the V(s) bias head can
    emit large values). On these pursuit/PCP rewards that produced Q_tot ~ +700 vs a
    true return ~ -70 on a smoke run. We therefore start the mixer near-identity-scale:
    the V(s) bias head (hyper_b2) is zero-initialized so Q_tot starts ~0 and learns its
    scale from rewards, and the weight hypernets are shrunk so initial |W| is small
    (still > 0 — monotonicity is untouched). This only changes the starting point.
    """

    _W_INIT_SCALE = 0.1   # shrink weight-hypernet init so Q_tot ~ 0 (not inflated) at start

    def __init__(self, num_agents, state_dim, embed_dim=32, hypernet_embed=64, device="cpu"):
        super().__init__()

        self.N = num_agents
        self.state_dim = state_dim
        self.embed = embed_dim
        self.device = torch.device(device)
        # |.| applied at forward time enforces non-negativity (monotonicity)
        self.hyper_w1 = nn.Linear(state_dim, self.embed * self.N)
        self.hyper_w2 = nn.Linear(state_dim, self.embed)
        self.hyper_b1 = nn.Linear(state_dim, self.embed)
        self.hyper_b2 = nn.Sequential(nn.Linear(state_dim, hypernet_embed), nn.ReLU(),
                                      nn.Linear(hypernet_embed, 1))

        # Stability init (see class docstring): small positive mixing weights + zero V(s).
        with torch.no_grad():
            self.hyper_w1.weight.mul_(self._W_INIT_SCALE); self.hyper_w1.bias.mul_(self._W_INIT_SCALE)
            self.hyper_w2.weight.mul_(self._W_INIT_SCALE); self.hyper_w2.bias.mul_(self._W_INIT_SCALE)
            nn.init.zeros_(self.hyper_b2[-1].weight); nn.init.zeros_(self.hyper_b2[-1].bias)

        self.to(self.device)

    def forward(self, agent_qs, state):
        # agent_qs: [B, N]  (chosen-action or max Q per agent);  state: [B, state_dim]
        B = agent_qs.shape[0]
        w1 = torch.abs(self.hyper_w1(state)).reshape(B, self.N, self.embed)   # [B, N, embed]  >= 0
        b1 = self.hyper_b1(state).reshape(B, 1, self.embed)
        hidden = F.elu(torch.bmm(agent_qs.reshape(B, 1, self.N), w1) + b1)    # [B, 1, embed]
        w2 = torch.abs(self.hyper_w2(state)).reshape(B, self.embed, 1)        # [B, embed, 1]  >= 0
        b2 = self.hyper_b2(state).reshape(B, 1, 1)                            # state-only V(s) bias
        q_tot = torch.bmm(hidden, w2) + b2                                    # [B, 1, 1]

        return q_tot.reshape(B, 1)

    @torch.no_grad()
    def weight_min(self, state) -> float:
        """Min over the abs'd mixing weights on this batch's state. >= 0 by construction;
        surfaced so the trainer can assert monotonicity in metrics.csv (spec 4c) and catch
        any NaN / removed-abs regression."""
        w1 = torch.abs(self.hyper_w1(state))
        w2 = torch.abs(self.hyper_w2(state))
        return torch.minimum(w1.min(), w2.min()).item()
